const contexts=[];
async function context(){
  const ctx=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  contexts.push(ctx);
  const page=await ctx.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  return page;
}
async function capture(page,name,selector){
  await page.evaluate(()=>document.fonts.ready);
  const target=selector?page.locator(selector):page;
  await target.screenshot({path:directory+'/'+name+'.png',...(selector?{}:{fullPage:false})});
  screenshots.push({name,path:name+'.png',url:page.url()});
}
async function go(page,path){
  await page.goto(baseURL+'/?evidence='+Date.now()+'#'+path);
  await page.locator('#main').waitFor({state:'visible'});
  await page.locator('.page-loading').waitFor({state:'hidden'});
}
async function login(role){
  const page=await context();
  await page.goto(baseURL);
  const response=await page.request.post(baseURL+'/api/auth/login',{data:{email:role+'@may.local',password:'MayDemo2026!'}});
  assert.equal(response.status(),200);
  await page.reload();
  await page.locator('.page-loading').waitFor({state:'hidden'});
  await go(page,'/admin');
  return page;
}
