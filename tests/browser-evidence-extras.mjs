import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {writeFile} from 'node:fs/promises';
const baseURL=process.env.MAY_TEST_BASE_URL||'http://127.0.0.1:8767';
const browser=await chromium.launch({executablePath:process.env.MAY_BROWSER_PATH||'/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--enable-unsafe-swiftshader']});
const directory='output/screenshots';
const records=[];
try{
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 async function go(path){await page.goto(baseURL+'/?capture='+Date.now()+'#'+path);await page.locator('#main').waitFor();await page.locator('.page-loading').waitFor({state:'hidden'});}
 async function cap(name,selector){await page.evaluate(()=>document.fonts.ready);await (selector?page.locator(selector):page).screenshot({path:directory+'/'+name+'.png'});records.push({name,path:name+'.png'});}
 await go('/shop');
 await page.locator('[data-action="voice"]').first().click();
 await page.route('**/api/search/transcribe',route=>route.fulfill({json:{text:'áo len nữ',language_code:'vie',provider:'elevenlabs'}}));
 const wav=Buffer.alloc(32044);wav.write('RIFF');wav.writeUInt32LE(32036,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(16000,24);wav.writeUInt32LE(32000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(32000,40);
 await page.locator('#audio-file').setInputFiles({name:'controlled-speech.wav',mimeType:'audio/wav',buffer:wav});
 await page.locator('#transcribe-audio').click();
 await page.locator('#transcript-form').waitFor();
 assert.equal(await page.locator('#transcript').inputValue(),'áo len nữ');
 await cap('28-editable-transcript-controlled','#transcript-form');
 await page.locator('#transcript').fill('áo len');
 await page.locator('#transcript-form button').click();
 await page.locator('.product-card').first().waitFor();
 const products=await (await page.request.get(baseURL+'/api/products')).json();
 const p=products[0];
 await page.request.post(baseURL+'/api/cart',{data:{variant_id:p.variants[0].id,quantity:1}});
 await go('/checkout');
 await page.locator('#voucher-code').fill('HELLOMAY');
 const quote=page.waitForResponse(r=>r.url().endsWith('/api/checkout/quote')&&r.request().method()==='POST');
 await page.locator('[data-action="apply-voucher"]').click();
 assert.equal((await (await quote).json()).voucher,'HELLOMAY');
 await page.locator('#voucher-message').filter({hasText:'Đã áp dụng'}).waitFor();
 await cap('33-voucher-quote');
 const cancelQuote=await (await page.request.post(baseURL+'/api/checkout/quote',{data:{}})).json();
 const placed=await page.request.post(baseURL+'/api/orders',{data:{recipient_name:'Khách minh họa hủy đơn',phone:'0901234567',address:'123 Đường Minh Họa, Hà Nội',expected_total:cancelQuote.total,payment_method:'cod',idempotency_key:'cancel-evidence-'+Date.now()}});
 assert.equal(placed.status(),201);
 const order=await placed.json();
 await go('/orders');
 await page.locator('[data-report="cancel-order"][data-id="'+order.id+'"]').click();
 await page.locator('#cancel-order-form textarea').fill('Cần thay đổi địa chỉ nhận hàng');
 await cap('29-cancellation-request','#modal');
 await page.locator('#cancel-order-form button[type="submit"]').click();
 await page.locator('#modal').waitFor({state:'hidden'});
 await go('/orders');
 await cap('30-cancelled-order','#order-'+order.id);
 await go('/shop');
 await page.locator('[data-action="favorite"]').first().click();
 await go('/favorites');
 await page.locator('.product-card').first().waitFor();
 await cap('31-favorites');
 await go('/vouchers');
 await cap('32-vouchers');
 await go('/try-on');
 await page.locator('#start-camera').click();
 await page.locator('#camera-badge.camera-live').waitFor();
 await cap('34-camera-preview');
 await go('/shop');
 await writeFile(directory+'/extras-manifest.json',JSON.stringify({screenshots:records,controlled_speech:true,synthetic_camera:true},null,2));
 console.log('Additional browser evidence passed: editable transcript (controlled provider response), voucher quote, cancellation, favorites and synthetic camera.');
}finally{await browser.close();}
